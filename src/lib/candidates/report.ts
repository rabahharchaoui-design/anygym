// The coverage report (PLAN 3.5e), as text: reports/coverage-3.5e.md. Pure, so the script only reads
// and writes files and the test checks the same text.
import { coverageTable, groupRows, presetRows, type CoverageRow, type Move } from './coverage';
import { PRESET_KITS } from './presets';
import { STYLES, type CandidateRecord } from './types';
import { supports } from '../swap';

export interface ReportInput {
  sure: readonly Move[];
  candidates: readonly CandidateRecord[];
  /** The 17 ladder patterns, then the extra groups. */
  groups: readonly string[];
  dropped: number;
  sourceTotal: number;
  catalogTotal: number;
}

export interface Report {
  presets: CoverageRow[];
  groups: CoverageRow[];
  text: string;
}

const asMove = (c: CandidateRecord): Move => ({ id: c.id, group: c.pattern, requires: c.requires, ladder: c.ladder });

export function coverageReport(input: ReportInput): Report {
  const moves = input.candidates.map(asMove);
  const presets = presetRows(input.sure, moves, PRESET_KITS);
  const groups = groupRows(input.sure, moves, input.groups);
  const byStyle = STYLES.map((s) => `| ${s} | ${input.candidates.filter((c) => c.styles[0] === s).length} | ${input.candidates.filter((c) => c.styles.includes(s)).length} |`);
  const perPreset = PRESET_KITS.map((p) => `| ${p.label} | ${moves.filter((m) => supports(m.requires, p.kit)).length} |`);
  const short = [...presets.filter((r) => r.ifAllLadder < r.target), ...groups.filter((r) => r.ifAll < r.target)];
  const text = [
    '# Coverage report (PLAN 3.5e)',
    '',
    'Generated by scripts/coverage-report.ts from data/patterns.json, data/exercise-map.json, data/catalog-demos.json and',
    'data/catalog-candidates.json. "Sure today" counts the swap ladder moves with a sure demo (what Quick workout, swaps,',
    'Up next and the generator can use). "If every candidate is approved" adds every candidate the place can do; a',
    'candidate only counts for real once G approves it on the Review screen.',
    '',
    `Source: ${input.sourceTotal} exercises upstream, ${input.catalogTotal} in the catalog, ${input.candidates.length} candidates, ${input.dropped} more dropped after the builder's photo check.`,
    '',
    '## Places (target: 25 sure moves each)',
    '',
    ...coverageTable('Place', presets, true),
    '',
    'The verdict counts only strength and core moves (the swap ladders), so a place never meets its target on stretches alone.',
    '',
    'Home here is the SPEC 3 home picks (dumbbells 5 to 50 lb, bands, a pull up bar); Dumbbells only is a 5 to 50 lb rack;',
    'Outdoors is a park with a pull up bar; Bodyweight is no equipment at all.',
    '',
    '## Movement patterns (target: 3 sure moves each)',
    '',
    'The 17 swap ladder patterns, then the groups that are not ladders (cardio, mobility, power, accessory): those are',
    'counted here but only reach a workout once a later item gives them a place (the Cardio and Mobility styles).',
    '',
    ...coverageTable('Pattern', groups),
    '',
    '## Candidates per style',
    '',
    '| Style | Main style | Tagged |',
    '|---|---|---|',
    ...byStyle,
    '',
    '## Candidates each place can do',
    '',
    '| Place | Candidates |',
    '|---|---|',
    ...perPreset,
    '',
    '## Still short if every candidate is approved',
    '',
    ...(short.length ? short.map((r) => `- ${r.label}: ${r.ifAllLadder} of ${r.target}`) : ['- Nothing.']),
    '',
    'Lunge and quads isolation stay short because the source has no more of them with clear photos and gear the app',
    'knows. The catalog already holds lunges (Dumbbell_Lunges, Dumbbell_Rear_Lunge, Barbell_Lunge, Bodyweight_Walking_Lunge,',
    'Split_Squats) and Single-Leg_Leg_Extension whose photos were never checked by hand, so they have no sure demo yet:',
    'checking those photos (data/catalog-demos.json) is the quickest way to close both gaps.',
    '',
  ].join('\n');
  return { presets, groups, text };
}
