// Builds the candidate moves (PLAN 3.5e). Run: npm run candidates [-- --fetch] [-- --photos] [-- --sheets DIR]
//   --fetch   downloads yuhonas/free-exercise-db at the pinned SHA (data/catalog-source.json) and keeps
//             only the curated records in data/candidate-source.json (so normal runs need no network);
//   --photos  downloads and optimizes each candidate's two photos into public/exc/<id>/{0,1}.webp
//             (never under public/ex/, which scripts/build-catalog.ts replaces) and removes old ones;
//   --check   only compares with the committed data/catalog-candidates.json (exit 1 when it differs);
//   --sheets  writes contact sheets (20 candidates a page, both photos, the id under them) to DIR
//             for the builder's own photo check; never into the repo.
// Always: data/catalog-candidates.json from the curation, the source records, the catalog and the
// patterns, through src/lib/candidates/build.ts. Any problem stops it and nothing is written.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';
import { EQUIPMENT_IDS } from '../src/db/types.ts';
import { buildCandidates } from '../src/lib/candidates/build.ts';
import { checkMuscleFixes, parseCuration, type CurationFile } from '../src/lib/candidates/curation.ts';
import { MUSCLE_REGIONS } from '../src/lib/muscles.ts';
import { EXTRA_GROUPS, type CandidateFile, type SourceExercise } from '../src/lib/candidates/types.ts';

const root = new URL('../', import.meta.url).pathname;
const readJson = <T>(p: string): T => JSON.parse(readFileSync(root + p, 'utf8')) as T;
const args = process.argv.slice(2);
const has = (flag: string) => args.includes(flag);

const source = readJson<{ repo: string; sha: string; license: string }>('data/catalog-source.json');
const raw = `https://raw.githubusercontent.com/${source.repo}/${source.sha}`;
const curation = readJson<CurationFile>('data/candidate-curation.json');
const patterns = Object.keys(readJson<{ patterns: Record<string, unknown> }>('data/patterns.json').patterns);
const catalogIds = new Set(readJson<{ exercises: { id: string }[] }>('data/catalog.json').exercises.map((e) => e.id));
const LOADS = ['barbell', 'dumbbell_each', 'single', 'stack', 'plate_machine', 'bodyweight', 'timed', 'unknown'];
const BARS = ['olympic', 'womens', 'ez_curl', 'trap', 'smith'];

async function get(url: string): Promise<Buffer> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} for ${url}`);
  return Buffer.from(await res.arrayBuffer());
}

const { entries, problems: parseProblems } = parseCuration(curation, [...patterns, ...EXTRA_GROUPS], EQUIPMENT_IDS, LOADS, BARS);
parseProblems.push(...checkMuscleFixes(curation.muscles, Object.keys(MUSCLE_REGIONS), new Set(entries.map((e) => e.id))));
if (parseProblems.length) throw new Error('data/candidate-curation.json:\n' + parseProblems.join('\n'));

if (has('--fetch')) {
  const all = JSON.parse((await get(`${raw}/dist/exercises.json`)).toString('utf8')) as SourceExercise[];
  const wanted = new Set(entries.map((e) => e.id));
  const slice = all.filter((e) => wanted.has(e.id)).sort((a, b) => (a.id < b.id ? -1 : 1));
  writeFileSync(root + 'data/candidate-source.json', JSON.stringify({ repo: source.repo, sha: source.sha, license: source.license, total: all.length, exercises: slice }, null, 1) + '\n');
  console.log(`candidate-source.json: ${slice.length} source records`);
}

const slice = readJson<{ exercises: SourceExercise[] }>('data/candidate-source.json').exercises;
const result = buildCandidates({ entries, source: new Map(slice.map((e) => [e.id, e])), catalogIds, patterns, photos: curation.photos, muscles: curation.muscles });
if (result.problems.length) throw new Error('candidates:\n' + result.problems.join('\n'));

const out: CandidateFile = {
  about: 'PLAN 3.5e: candidate moves, generated by scripts/build-candidates.ts from data/candidate-curation.json. Never used in any suggestion, plan, swap, quick card, Up next or picker until G approves one on the Review screen (src/data/candidateGate.ts).',
  source: { repo: source.repo, sha: source.sha, license: source.license },
  candidates: result.candidates,
};
const text = JSON.stringify(out, null, 1) + '\n';
if (has('--check')) {
  const same = readFileSync(root + 'data/catalog-candidates.json', 'utf8') === text;
  console.log(same ? 'catalog-candidates.json: up to date' : 'catalog-candidates.json: out of date (run npm run candidates)');
  process.exit(same ? 0 : 1);
}
writeFileSync(root + 'data/catalog-candidates.json', text);
console.log(`catalog-candidates.json: ${result.candidates.length} candidates, ${result.dropped.length} dropped after the photo check`);

if (has('--photos')) {
  const dir = root + 'public/exc/';
  mkdirSync(dir, { recursive: true });
  const keep = new Set(result.candidates.map((c) => c.id));
  for (const old of readdirSync(dir)) if (!keep.has(old)) rmSync(dir + old, { recursive: true, force: true });
  const todo = result.candidates.filter((c) => !existsSync(`${dir}${c.id}/1.webp`));
  let next = 0;
  const work = async () => {
    while (next < todo.length) {
      const c = todo[next++]!;
      const s = slice.find((e) => e.id === c.id)!;
      mkdirSync(dir + c.id, { recursive: true });
      for (let i = 0; i < 2; i++) {
        const img = sharp(await get(`${raw}/exercises/${s.images[i]}`)).rotate().resize({ width: 600, withoutEnlargement: true });
        await img.webp({ quality: 66 }).toFile(`${dir}${c.id}/${i}.webp`);
      }
    }
  };
  await Promise.all(Array.from({ length: 6 }, work));
  console.log(`public/exc: ${keep.size} candidates (${todo.length} downloaded now)`);
}

const sheetsAt = args.indexOf('--sheets');
if (sheetsAt >= 0) {
  const outDir = args[sheetsAt + 1];
  if (!outDir || outDir.startsWith(root)) throw new Error('--sheets needs a folder outside the repo');
  mkdirSync(outDir, { recursive: true });
  const W = 150, H = 100, LABEL = 26, PER = 20, COLS = 4;
  // --new: only candidates the curation has no photo note for yet.
  const list = has('--new') ? result.candidates.filter((c) => !curation.photos[c.id]) : result.candidates;
  for (let p = 0; p * PER < list.length; p++) {
    const page = list.slice(p * PER, (p + 1) * PER);
    const rows = Math.ceil(page.length / COLS);
    const layers: sharp.OverlayOptions[] = [];
    for (const [i, c] of page.entries()) {
      const x = (i % COLS) * (2 * W + 10), y = Math.floor(i / COLS) * (H + LABEL);
      for (let k = 0; k < 2; k++) layers.push({ input: await sharp(`${root}public/exc/${c.id}/${k}.webp`).resize(W, H, { fit: 'contain', background: '#fff' }).toBuffer(), left: x + k * W, top: y });
      const text = `${p * PER + i + 1} ${c.id}`.replace(/&/g, '&amp;').slice(0, 44);
      layers.push({ input: Buffer.from(`<svg width="${2 * W}" height="${LABEL}"><text x="2" y="17" font-size="13" font-family="Helvetica">${text}</text></svg>`), left: x, top: y + H });
    }
    await sharp({ create: { width: COLS * (2 * W + 10), height: rows * (H + LABEL), channels: 3, background: '#fff' } }).composite(layers).png().toFile(`${outDir}/sheet-${String(p + 1).padStart(2, '0')}.png`);
  }
  console.log(`contact sheets in ${outDir}`);
}
