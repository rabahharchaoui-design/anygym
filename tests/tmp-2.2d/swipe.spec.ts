import { expect, test } from '../fixtures';
import { pickExercises, exerciseView } from '../workout-helpers';
test('dbg', async ({ page }) => {
  await page.goto('./');
  await page.getByRole('button', { name: /Quick workout/ }).tap();
  await pickExercises(page, [['back squat', 'Barbell Back Squat']]);
  const view = exerciseView(page, 'barbell-back-squat');
  await expect(view.getByTestId('set-todo')).toHaveCount(3);
  await page.waitForTimeout(600);
  await page.evaluate(() => { (window as any).__ev = []; for (const t of ['pointerdown','pointermove','pointerup','pointercancel','mousedown','click']) document.addEventListener(t, (e: any) => (window as any).__ev.push(t + ':' + (e.pointerType ?? '') + ':' + Math.round(e.clientX)), true); });
  const row = view.getByTestId('set-todo').nth(1);
  const b = (await row.boundingBox())!;
  const y = b.y + b.height / 2, x0 = b.x + b.width - 24;
  await page.mouse.move(x0, y); await page.mouse.down();
  for (let i = 1; i <= 10; i++) await page.mouse.move(x0 - 11 * i, y);
  console.log('mid', await row.evaluate((el) => el.style.transform));
  await page.mouse.up();
  await page.waitForTimeout(400);
  console.log(await page.evaluate(() => (window as any).__ev.join(' ')));
  console.log('end', await row.evaluate((el) => el.style.transform), await row.evaluate((el) => el.parentElement!.getAttribute('data-revealed')));
});
